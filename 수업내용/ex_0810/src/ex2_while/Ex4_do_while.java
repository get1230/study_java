package ex2_while;

public class Ex4_do_while {
    public static void main(String[] args) {
        
        //do-while문
        // 선 처리 후 비교

        int i = 11;

        do{

            System.out.println(i);                
            i++;

            // 참이면 반복하는 부분

            }while(i <= 10 );
        }


    }

